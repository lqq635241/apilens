import type { ApiSpec } from '../types'
import { deref, refName } from './openapi'

function pascal(name: string): string {
  return name
    .replace(/[-_\s]+(.)?/g, (_, c) => (c ? c.toUpperCase() : ''))
    .replace(/^(.)/, (c) => c.toUpperCase())
}

function schemaToTs(doc: any, schema: any, depth = 0): string {
  if (!schema) return 'unknown'
  if (schema.$ref) return pascal(refName(schema) ?? 'object')
  const s = deref(doc, schema)
  if (!s) return 'unknown'
  if (s.$ref) return pascal(refName(s) ?? 'object')

  if (Array.isArray(s.enum) && s.enum.length) {
    return s.enum.map((v: any) => JSON.stringify(v)).join(' | ')
  }
  if (Array.isArray(s.oneOf)) return s.oneOf.map((x: any) => schemaToTs(doc, x, depth + 1)).join(' | ')
  if (Array.isArray(s.allOf)) {
    return s.allOf.map((x: any) => schemaToTs(doc, x, depth + 1)).join(' & ')
  }
  if (s.type === 'array' || s.items) {
    const inner = schemaToTs(doc, s.items ?? {}, depth + 1)
    return /[ |&]/.test(inner) ? `(${inner})[]` : `${inner}[]`
  }
  if (s.type === 'object' || s.properties) {
    const props = s.properties ?? {}
    const keys = Object.keys(props)
    if (keys.length === 0) return 'Record<string, unknown>'
    if (depth >= 1) return 'Record<string, unknown>'
    const inner = keys
      .map((k) => `${k}${s.required?.includes(k) ? '' : '?'}: ${schemaToTs(doc, props[k], depth + 1)}`)
      .join('; ')
    return `{ ${inner} }`
  }

  switch (s.type) {
    case 'integer':
    case 'number':
      return 'number'
    case 'boolean':
      return 'boolean'
    case 'string':
      return 'string'
    case 'null':
      return 'null'
    default:
      return 'unknown'
  }
}

/** 单个资源 schema → TS interface 代码 */
export function generateResourceType(doc: any, schemaName: string, schema: any): string {
  const s = deref(doc, schema)
  const required: string[] = s.required ?? []
  const name = pascal(schemaName)
  const lines: string[] = [`export interface ${name} {`]
  for (const [key, prop] of Object.entries<any>(s.properties ?? {})) {
    const desc = deref(doc, prop)?.description
    if (desc) lines.push(`  /** ${desc} */`)
    const isRequired = required.includes(key)
    lines.push(`  ${key}${isRequired ? '' : '?'}: ${schemaToTs(doc, prop)}`)
  }
  lines.push('}')
  return lines.join('\n')
}

/** 整份文档 → TS 类型文件（包含请求体等辅助 schema） */
export function generateTypes(spec: ApiSpec): string {
  const parts: string[] = [
    `// Generated by ApiLens from "${spec.title}"${spec.version ? ` v${spec.version}` : ''}`,
    `// ${new Date().toISOString()}`,
    '',
  ]
  const schemas = spec.doc?.components?.schemas ?? {}
  for (const [schemaName, schema] of Object.entries<any>(schemas)) {
    const s = deref(spec.doc, schema)
    if (!s?.properties) continue
    parts.push(generateResourceType(spec.doc, schemaName, schema), '')
  }
  return parts.join('\n').trim() + '\n'
}
