import type { ApiSpec } from '../types'
import { mockFromSchema } from './mock'

/** /orders/{id} → /orders/:id */
function mswPath(path: string): string {
  return path.replace(/\{([^}]+)\}/g, ':$1')
}

function pickSuccessSchema(endpoint: { responses: { code: string; schema?: any }[] }) {
  const ok = endpoint.responses.find((r) => /^2\d\d$/.test(r.code) && r.schema)
  return ok?.schema
}

/** 单个接口的 MSW handler 代码 */
export function generateHandler(spec: ApiSpec, endpointId: string): string {
  const ep = spec.endpoints.find((e) => e.id === endpointId)
  if (!ep) return ''
  const schema = pickSuccessSchema(ep)
  const isList = ep.method === 'GET' && !/\{[^}]+\}$/.test(ep.path)
  let value: any = schema ? mockFromSchema(spec.doc, schema) : { ok: true }
  if (isList && !Array.isArray(value)) value = [value, value]

  const method = ep.method.toLowerCase()
  const fn = method === 'delete' ? 'http.delete' : `http.${method}`
  return `${fn}('${mswPath(ep.path)}', ({ params }) => {
  // ${ep.summary || endpointId}
  return HttpResponse.json(${JSON.stringify(value, null, 2).replace(/\n/g, '\n  ')}, { status: 200 })
})`
}

/** 整份文档 → MSW handlers 文件 */
export function generateMsw(spec: ApiSpec): string {
  const lines: string[] = [
    `// Generated by ApiLens from "${spec.title}"${spec.version ? ` v${spec.version}` : ''}`,
    `// 安装：npm i -D msw`,
    `import { http, HttpResponse } from 'msw'`,
    '',
    'export const handlers = [',
  ]
  for (const ep of spec.endpoints) {
    const schema = pickSuccessSchema(ep)
    if (!schema) continue
    const isList = ep.method === 'GET' && !/\{[^}]+\}$/.test(ep.path)
    let value: any = mockFromSchema(spec.doc, schema)
    if (isList && !Array.isArray(value)) value = [value, value]
    const method = ep.method.toLowerCase()
    const fn = method === 'delete' ? 'http.delete' : `http.${method}`
    const body = JSON.stringify(value, null, 2).replace(/\n/g, '\n  ')
    lines.push(`  // ${ep.summary || `${ep.method} ${ep.path}`}`)
    lines.push(`  ${fn}('${mswPath(ep.path)}', () => HttpResponse.json(${body})),`, '')
  }
  lines.push(']', '')
  return lines.join('\n')
}

/** 单个资源的 JSON 示例 */
export function resourceExample(spec: ApiSpec, resourceKey: string): string {
  const res = spec.resources.find((r) => r.key === resourceKey)
  if (!res?.schema) return '{}'
  return JSON.stringify(mockFromSchema(spec.doc, res.schema), null, 2)
}
